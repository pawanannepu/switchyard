// Regenerates the protocol schema from the Rust types, then the TS types from the schema.
//
//   node scripts/generate.mjs          write crates/sy-protocol/protocol.schema.json and src/generated/*
//   node scripts/generate.mjs --check  fail (exit 1) if any committed file differs from a fresh generation

import { execFileSync } from "node:child_process";
import { readFileSync, writeFileSync, mkdirSync } from "node:fs";
import { dirname, join, relative } from "node:path";
import { fileURLToPath } from "node:url";
import { compile } from "json-schema-to-typescript";

const pkg = join(dirname(fileURLToPath(import.meta.url)), "..");
const root = join(pkg, "../..");
const schemaPath = join(root, "crates/sy-protocol/protocol.schema.json");
const typesPath = join(pkg, "src/generated/types.ts");
const methodsPath = join(pkg, "src/generated/methods.ts");
const check = process.argv.includes("--check");

const banner = "// Generated by packages/protocol-ts/scripts/generate.mjs from crates/sy-protocol. Do not edit.\n";

const schemaText = execFileSync("cargo", ["run", "-q", "-p", "sy-protocol", "--bin", "gen-schema"], {
  cwd: root,
  encoding: "utf8",
});
const schema = JSON.parse(schemaText);

// Compile only the definitions: the root is a catalog, not a type.
const catalog = { $defs: schema.$defs, title: "ProtocolCatalog", type: "object", additionalProperties: false };
let types = await compile(catalog, "ProtocolCatalog", {
  bannerComment: banner,
  additionalProperties: false,
  unreachableDefinitions: true,
  declareExternallyReferenced: true,
  strictIndexSignatures: true,
  format: true,
});
types = types.replace(/export interface ProtocolCatalog \{\}\n\n?/, "");

const methods = schema["x-methods"];
const requests = methods.filter((m) => m.kind === "request");
const notifications = methods.filter((m) => m.kind === "notification");
const q = (s) => JSON.stringify(s);
const methodsTs = [
  banner,
  'import type * as T from "./types.ts";',
  "",
  "/** The protocol version this build speaks. Majors must match; minors only add things. */",
  `export const PROTOCOL = ${JSON.stringify(schema["x-protocol"])} as const;`,
  "",
  "/** Size limits the engine enforces, in bytes. */",
  `export const LIMITS = ${JSON.stringify(schema["x-limits"], null, 2)} as const;`,
  "",
  "/** Every JSON-RPC error code the protocol uses, by name. */",
  `export const ErrorCode = ${JSON.stringify(schema["x-error-codes"], null, 2)} as const;`,
  "/** The name of an error code, such as `RunNotFound`. */",
  "export type ErrorCodeName = keyof typeof ErrorCode;",
  "",
  "/** Every request: its params and result types. */",
  "export interface Requests {",
  ...requests.map((m) => `  ${q(m.name)}: { params: T.${m.params}; result: T.${m.result} };`),
  "}",
  "",
  "/** Every notification: its params type. */",
  "export interface Notifications {",
  ...notifications.map((m) => `  ${q(m.name)}: T.${m.params};`),
  "}",
  "",
  "/** Work before `session.hello` and after an incompatible one. */",
  `export const STABLE_METHODS = [${requests
    .filter((m) => m.stable)
    .map((m) => q(m.name))
    .join(", ")}] as const;`,
  "",
  "/** Answered only by engines built with the `devtools` feature. */",
  `export const DEV_METHODS = [${requests
    .filter((m) => m.dev_only)
    .map((m) => q(m.name))
    .join(", ")}] as const;`,
  "",
].join("\n");

const outputs = [
  [schemaPath, schemaText],
  [typesPath, types],
  [methodsPath, methodsTs],
];

if (check) {
  const drifted = outputs.filter(([path, fresh]) => {
    try {
      return readFileSync(path, "utf8") !== fresh;
    } catch {
      return true;
    }
  });
  if (drifted.length > 0) {
    console.error("Protocol drift: these files don't match the Rust types in crates/sy-protocol:");
    for (const [path] of drifted) console.error(`  ${relative(root, path)}`);
    console.error("Run `pnpm protocol:gen` and commit the result.");
    process.exit(1);
  }
  console.log("Protocol schema and TS types match the Rust source.");
} else {
  mkdirSync(dirname(typesPath), { recursive: true });
  for (const [path, text] of outputs) writeFileSync(path, text);
  console.log(`Wrote ${outputs.map(([p]) => relative(root, p)).join(", ")}`);
}
